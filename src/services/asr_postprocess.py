def postprocess(text: str) -> str:
    """ASR 輸出後處理：簡轉繁 + 詞彙修正"""
    # Step 1: opencc 簡轉繁
    text = _converter.convert(text)
    # Step 2: 領域詞彙修正（opencc 轉完可能仍有錯）
    for wrong, correct in _CORRECTIONS.items():
        if wrong in text:
            text = text.replace(wrong, correct)
    return text.strip()
